import vm from 'node:vm';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const context=vm.createContext({window:{}});
for(const file of ['exam-core.js','data-exam-demo.js'])vm.runInContext(readFileSync('dist/'+file,'utf8'),context);
const C=context.window.QingheExamCore,paper=C.validatePaper(context.window.QINGHE_EXAM_DEMO);
const result=C.grade(paper,{'demo-l1':0,'demo-r1':1,'demo-r2':'  起床  ','demo-r3':0,'demo-w1':'我喜欢面条。'});
assert.equal(result.earned,20);assert.equal(result.objectiveMax,20);assert.equal(result.pendingMax,10);assert.equal(result.wrongIds.length,0);
const missing=C.grade(paper,{});assert.equal(missing.earned,0);assert.equal(missing.wrongIds.length,4);assert.equal(missing.rows[4].pending,true);
assert.equal(C.answered(C.flatten(paper)[0],0),true);assert.equal(C.answered(C.flatten(paper)[0],undefined),false);
const copy=()=>JSON.parse(JSON.stringify(paper));
let p=copy();p.sections[0].questions[0].answer=99;assert.throws(()=>C.validatePaper(p));
p=copy();p.sections[0].questions[0].id=p.sections[1].questions[0].id;assert.throws(()=>C.validatePaper(p));
p=copy();p.demo=false;assert.throws(()=>C.validatePaper(p));
p=copy();p.sections[0].questions[0].audio='javascript:alert(1)';assert.throws(()=>C.validatePaper(p));
p=copy();p.demo=false;p.sections[0].questions[0].audio='audio/exams/demo-l1.mp3';assert.equal(C.validatePaper(p).demo,false);
p=copy();p.durationMinutes=0;assert.throws(()=>C.validatePaper(p));
p=copy();p.sections[2].questions[0].rubric='';assert.throws(()=>C.validatePaper(p));
C.validatePaper(JSON.parse(readFileSync('dist/exam-paper-template.json','utf8')));
console.log('Exam validation and grading checks passed (including zero-index answers, unanswered items, manual writing, unsafe audio and duplicate IDs).');
